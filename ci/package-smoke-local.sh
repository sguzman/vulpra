#!/usr/bin/env bash
# Standalone incremental package + isolated runtime test for Vulpra.
# May be downloaded to ~/ and run without updating the source checkout.
set -Eeuo pipefail
REPO="${1:-$HOME/Code/Apps/vulpra}"
cd "$REPO" || { echo "ERROR: Missing repo: $REPO" >&2; exit 2; }
REPO=$(pwd -P)
[[ -f mach ]] || { echo 'ERROR: mach missing.' >&2; exit 2; }
[[ "$(git config --bool core.sparseCheckout || true)" != true ]] || {
  echo 'ERROR: Source checkout still sparse.' >&2; exit 3;
}
OBJ="$REPO/obj-vulpra-linux"
BIN="$OBJ/dist/bin"
[[ -s "$BIN/application.ini" ]] && grep -Fxq 'Name=Vulpra' "$BIN/application.ini" || {
  echo 'ERROR: Native Vulpra application.ini missing or incorrect.' >&2; exit 4;
}
# The executable may be named firefox or vulpra; the display name is Vulpra.
BROWSER=""
for candidate in vulpra firefox; do
  if [[ -x "$BIN/$candidate" ]]; then BROWSER="$candidate"; break; fi
done
[[ -n "$BROWSER" ]] || { echo 'ERROR: Native browser executable missing.' >&2; exit 4; }
export MOZCONFIG="${MOZCONFIG:-$HOME/.mozbuild/vulpra-local.mozconfig}"
[[ -f "$MOZCONFIG" ]] || { echo 'ERROR: Local mozconfig missing.' >&2; exit 4; }
LOGDIR=$(git rev-parse --path-format=absolute --git-path vulpra-native-build)
mkdir -p "$LOGDIR/packages"
exec 9>"$LOGDIR/build.lock"
flock -n 9 || { echo 'ERROR: Another build or package already running.' >&2; exit 7; }
STAMP=$(date +%Y%m%d-%H%M%S-%N)
LOG="$LOGDIR/package-smoke-$STAMP.log"
printf 'Native executable: %s/%s\n' "$BIN" "$BROWSER" | tee -a "$LOG"
# Native compile artifacts are preserved by Mozilla's incremental packaging.
set +e
./mach package 2>&1 | tee -a "$LOG"
result=("${PIPESTATUS[@]}")
set -e
((result[1] == 0)) || { echo 'ERROR: Packaging log could not be written.' >&2; exit 6; }
((result[0] == 0)) || { echo "ERROR: Packaging failed (exit ${result[0]})." >&2; exit "${result[0]}"; }
mapfile -d '' -t archives < <(
  find "$OBJ/dist" -maxdepth 1 -type f \( -name '*.tar.xz' -o -name '*.tar.bz2' -o -name '*.tar.gz' \) -printf '%T@ %p\0' |
    sort -zrn | cut -z -d ' ' -f2-
)
(("${#archives[@]}" > 0)) || { echo 'ERROR: No tarball generated by mach package.' >&2; exit 5; }
WORK=$(mktemp -d)
trap 'rm -rf -- "$WORK"' EXIT
APPDIR=""
ARCHIVE=""
for candidate in "${archives[@]}"; do
  mkdir -p "$WORK/unpack"
  if tar -xf "$candidate" -C "$WORK/unpack" >> "$LOG" 2>&1; then
    mapfile -d '' -t inis < <(find "$WORK/unpack" -mindepth 1 -maxdepth 4 -type f -name application.ini -print0)
    if (("${#inis[@]}" == 1)); then
      d=$(dirname "${inis[0]}")
      if [[ -x "$d/$BROWSER" ]] && grep -Fxq 'Name=Vulpra' "$d/application.ini"; then
        APPDIR="$d"
        ARCHIVE="$candidate"
        break
      fi
    fi
  fi
  rm -rf -- "$WORK/unpack"
done
[[ -n "$APPDIR" ]] || { echo 'ERROR: No archive contains a matching Vulpra executable and application.ini.' >&2; exit 5; }
echo "Package source: $ARCHIVE" | tee -a "$LOG"
# Never overwrite a native executable that happens to be named "vulpra".
[[ ! -e "$APPDIR/vulpra-launch" ]] || { echo 'ERROR: Launcher name collision.' >&2; exit 5; }
cat > "$APPDIR/vulpra-launch" <<'LAUNCH'
#!/usr/bin/env bash
set -Eeuo pipefail
umask 077
for arg in "$@"; do
  case "$arg" in
    -P|-P?*|-p|-p?*|--profile|--profile=*|-profile|-profile=*|--ProfileManager|-ProfileManager|--profilemanager|-profilemanager)
      echo 'vulpra-launch: profile override refused' >&2; exit 2 ;;
  esac
done
root="${XDG_DATA_HOME:-$HOME/.local/share}/vulpra"
[[ "$root" == /* ]] || { echo 'vulpra-launch: XDG_DATA_HOME must be absolute' >&2; exit 2; }
profile="$root/default"
[[ ! -L "$root" && ! -L "$profile" ]] || { echo 'vulpra-launch: linked profile refused' >&2; exit 2; }
mkdir -p -m 0700 "$root" "$profile"
chmod 0700 "$root" "$profile"
here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
exec "$here/__NATIVE_BIN__" --no-remote --new-instance --profile "$profile" "$@"
LAUNCH
sed -i "s|__NATIVE_BIN__|$BROWSER|" "$APPDIR/vulpra-launch"
chmod 0755 "$APPDIR/vulpra-launch"
OUT="$LOGDIR/packages/vulpra-local-$STAMP.tar.xz"
tar -cJf "$OUT" -C "$WORK/unpack" .
(cd "$(dirname "$OUT")" && sha256sum "$(basename "$OUT")" > "$(basename "$OUT").sha256")
(cd "$(dirname "$OUT")" && sha256sum -c "$(basename "$OUT").sha256") | tee -a "$LOG"
mkdir -p "$WORK/home" "$WORK/test"
cat > "$WORK/test/smoke.html" <<'HTML'
<!doctype html><html lang="en"><meta charset="utf-8"><title>Vulpra package smoke</title>
<h1>Vulpra compiled package</h1>
<script>document.querySelector('h1').textContent='Vulpra executed JavaScript';</script>
HTML
set +e
HOME="$WORK/home" XDG_DATA_HOME="$WORK/home/.local/share" MOZ_HEADLESS=1 \
  timeout "${VULPRA_HEADLESS_TIMEOUT:-120}" "$APPDIR/vulpra-launch" \
  --headless --screenshot "$WORK/test/smoke.png" "file://$WORK/test/smoke.html" 2>&1 | tee -a "$LOG"
result=("${PIPESTATUS[@]}")
set -e
((result[1] == 0)) || { echo 'ERROR: Smoke log not written.' >&2; exit 6; }
((result[0] == 0)) || { echo "ERROR: Packaged browser startup failed (exit ${result[0]})." >&2; exit "${result[0]}"; }
[[ -s "$WORK/test/smoke.png" ]] || { echo 'ERROR: No screenshot produced.' >&2; exit 5; }
[[ "$(head -c 8 "$WORK/test/smoke.png" | od -An -tx1 | tr -d ' \n')" == 89504e470d0a1a0a ]] || {
  echo 'ERROR: Screenshot is not a PNG.' >&2; exit 5;
}
[[ -d "$WORK/home/.local/share/vulpra/default" && ! -e "$WORK/home/.mozilla" ]] || {
  echo 'ERROR: Browser profile isolation test failed.' >&2; exit 5;
}
cp "$WORK/test/smoke.png" "$LOGDIR/package-smoke-$STAMP.png"
echo 'PASS: Vulpra packaged and launched headlessly with private profile; archive checksum verified.' | tee -a "$LOG"
printf 'Package: %s\nScreenshot: %s\nLog: %s\n' "$OUT" "$LOGDIR/package-smoke-$STAMP.png" "$LOG" | tee -a "$LOG"
echo 'Wayland GUI and browser feature/security tests remain unverified.' | tee -a "$LOG"
